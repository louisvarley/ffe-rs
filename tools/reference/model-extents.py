"""Generate crates/ffe-convert/src/model_extents.rs from the JJFFE declarations.

Usage: model-extents.py <jjffe-master/ffebmp.asm> <output.rs>

The model table (DATA_004681, "Ship object table") lists one descriptor per
model. Command programs have no length field, so each program's physical extent
is the size of its labelled declaration block. The output holds layout numbers
only (extents and the descriptor's vertex count, normal count and scale used to
cross-check an executable), never program bytes.
"""
import re
import sys


def parse(path):
    labels, current = {}, None
    for line in open(path, encoding="latin-1"):
        match = re.match(r"^([A-Za-z_][A-Za-z_0-9]*):", line)
        if match:
            current = match.group(1)
            labels[current] = []
            continue
        text = line.split(";")[0].strip()
        if current is None or not text:
            continue
        keyword, _, rest = text.partition(" ")
        if keyword.upper() in ("SECTION", "GLOBAL", "EXTERN", "ALIGN"):
            continue
        values = [v.strip() for v in rest.split(",") if v.strip()]
        if keyword == "db":
            labels[current] += [("b", int(v, 0)) for v in values]
        elif keyword == "dw":
            labels[current] += [("w", int(v, 0)) for v in values]
        elif keyword == "dd":
            labels[current] += [("r", v) if v.startswith(("DATA_", "FUNC_", "JUMP_"))
                                else ("d", int(v, 0)) for v in values]
        elif keyword == "resb":
            labels[current].append(("z", int(rest, 0)))
        else:
            sys.exit(f"Unexpected declaration in {current}: {text}")
    return labels


def size(items):
    widths = {"b": 1, "w": 2, "d": 4, "r": 4}
    return sum(value if kind == "z" else widths[kind] for kind, value in items)


def fields(items):
    out = []
    for kind, value in items:
        if kind == "b":
            out.append(value)
        elif kind == "w":
            out += list(value.to_bytes(2, "little"))
        elif kind == "d":
            out += list((value & 0xFFFFFFFF).to_bytes(4, "little"))
        elif kind == "r":
            out += [value, None, None, None]
    return out


def dword(data, offset):
    if isinstance(data[offset], str):
        return data[offset]
    return int.from_bytes(bytes(data[offset:offset + 4]), "little")


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    labels = parse(sys.argv[1])
    # Read the table as 4-byte slots: a null entry is declared as four zero bytes.
    slots = fields(labels["DATA_004681"])
    if len(slots) % 4:
        sys.exit("Model table is not a whole number of pointers")
    rows = []
    for index in range(len(slots) // 4):
        descriptor = dword(slots, index * 4)
        if descriptor == 0:
            rows.append((0, 0, 0, 0))
            continue
        if not isinstance(descriptor, str):
            sys.exit(f"Model {index} table entry is neither a label nor null")
        data = fields(labels[descriptor])
        commands = dword(data, 0)
        vertices, normals, scale = dword(data, 8), dword(data, 16), dword(data, 20)
        if not isinstance(commands, str) or commands not in labels:
            sys.exit(f"Model {index} has no labelled command block")
        extent = size(labels[commands])
        if not (0 < extent <= 0xFFFF and vertices <= 255 and normals <= 255 and scale <= 31):
            sys.exit(f"Model {index} is outside the generated table's ranges")
        rows.append((extent, vertices, normals, scale))
    if (rows[74][0], rows[75][0]) != (516, 758):
        sys.exit("Station extents no longer match the verified 516/758 bytes")
    with open(sys.argv[2], "w", newline="\n") as output:
        output.write("//! Generated by tools/reference/model-extents.py from the JJFFE 2.8a7\n")
        output.write("//! model table declarations. Layout numbers only, no program bytes.\n\n")
        output.write(f"pub const MODEL_COUNT: usize = {len(rows)};\n\n")
        output.write("/// Physical command-program extent in bytes for each model table index;\n")
        output.write("/// zero for a null table entry (no model).\n")
        output.write(f"pub const COMMAND_EXTENTS: [u16; MODEL_COUNT] = [\n")
        for start in range(0, len(rows), 12):
            output.write("    " + ", ".join(str(r[0]) for r in rows[start:start + 12]) + ",\n")
        output.write("];\n\n")
        output.write("/// Declared (vertex count, normal count, scale) per index, to cross-check an\n")
        output.write("/// executable's descriptors against the declarations the extents came from.\n")
        output.write(f"pub const DESCRIPTOR_SHAPES: [(u8, u8, u8); MODEL_COUNT] = [\n")
        for start in range(0, len(rows), 6):
            output.write("    " + ", ".join(f"({r[1]}, {r[2]}, {r[3]})"
                                            for r in rows[start:start + 6]) + ",\n")
        output.write("];\n")
    print(f"{len(rows)} models written to {sys.argv[2]}")


if __name__ == "__main__":
    main()
