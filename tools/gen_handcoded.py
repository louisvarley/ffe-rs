"""Generate crates/ffe-core/src/handcoded.rs from the F875 call sequence in
jjffe-master/ffe.asm: the immediates passed to F873 (bodies) and F874 (starports)
and the zero terminators stored between systems. Run from the repository root."""
import re

L = open('jjffe-master/ffe.asm').read().split('\n')
first = next(i for i, l in enumerate(L) if l.startswith('FUNC_000875:'))
last = next(i for i, l in enumerate(L) if l.startswith('FUNC_000876:'))
ops, pushes, eax = [], [], None
for l in L[first:last]:
    t = l.split(';')[0].strip()
    if not t:
        continue
    m = re.match(r'push (?:byte|dword) ([+-]?0x[0-9a-f]+)$', t)
    if m:
        pushes.append(('i', int(m.group(1), 16)))
        continue
    if t == 'push ebx':
        pushes.append(('base', 0))
        continue
    m = re.match(r'lea eax,\[ebx\+(0x[0-9a-f]+)\]$', t)
    if m:
        eax = ('base', int(m.group(1), 16))
        continue
    m = re.match(r'lea eax,\[esi\+(0x[0-9a-f]+)\]$', t)
    if m:
        eax = ('name', int(m.group(1), 16))
        continue
    if t == 'push eax':
        pushes.append(eax)
        continue
    m = re.match(r'call FUNC_00087([34])$', t)
    if m:
        args = list(reversed(pushes))
        if args[0][0] == 'base' and args[-1] == ('base', 0) and len(args) in (15, 8):
            args = args[:-1]
        ops.append((int(m.group(1)), args))
        pushes = []
        continue
    m = re.match(r'mov \[ebx\+(0x[0-9a-f]+)\],eax$', t)
    if m:
        ops.append((0, [('base', int(m.group(1), 16))]))
        continue
    if t == 'push ebp' or t == 'push ebx' and not ops:
        pushes = []
out = ['//! Generated by tools/gen_handcoded.py from F875 in jjffe-master/ffe.asm: the',
       '//! arguments of the hand-coded bodies (F873), starports (F874) and the zero',
       '//! terminators between systems. The `name` is an offset into `DATA_007139`.',
       '', '/// One step of F875.', '#[derive(Debug, Clone, Copy, PartialEq, Eq)]',
       'pub enum Step {',
       '    /// F873 at the byte offset: mass-1, seed, p4, p5, parent, orbit, p8, p9, p10, p11, type, model, name.',
       '    Body(u32, [u32; 12], u32),',
       '    /// F874 at the byte offset: seed, latitude, longitude, parent, model, name.',
       '    Port(u32, [u32; 5], u32),',
       '    /// A zero mass dword at the byte offset ends a system\'s list.',
       '    End(u32),', '}', '', 'pub const STEPS: &[Step] = &[']
for kind, args in ops:
    if kind == 0:
        out.append(f'    Step::End({args[0][1]:#x}),')
    else:
        base = args[0][1]
        vals = [a[1] & 0xffffffff for a in args[1:-1]]
        name = args[-1][1]
        if kind == 3:
            assert len(vals) == 12, (len(vals), args)
            out.append(f'    Step::Body({base:#x}, {vals}, {name:#x}),'.replace('[', '[').replace(']', ']'))
        else:
            assert len(vals) == 5, (len(vals), args)
            out.append(f'    Step::Port({base:#x}, {vals}, {name:#x}),')
out.append('];')
open('crates/ffe-core/src/handcoded.rs', 'w').write('\n'.join(out) + '\n')
print(len(ops))
