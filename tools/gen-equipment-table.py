#!/usr/bin/env python3
"""Decode the original's 66-entry equipment table into Rust.

Source: ``ffedat.asm`` ``DATA_005289`` (66 records of 22 bytes). ``F383``
(``ffe.asm:28564``) lists them and ``F392`` dispatches each to its
category handler; ``F393`` reads record+0x12 as the equipment bit.

Record layout (from F383/F392):

    +0x00 dword  price           (times the tech multiplier)
    +0x04 dword  removal price   (same multiplier)
    +0x08 dword  mass (tonnes)   (the station's Wt column)
    +0x0c dword  unused (3 in every record)
    +0x10 byte   category/handler index (DATA_005297)
    +0x11 byte   flags (0x80 normally; 0 and 0x83 on three records)
    +0x12 byte   item code -- the equipment bit's selector for category 0,
                 the laser code for category 2, the missile code for
                 category 5, ...
    +0x13 byte   tech level
    +0x14 byte   used flag (F383's second price branch)
    +0x15 byte   pad

Names are ``DATA_005299`` codes 0x9875+n (index 0x75+n in that pointer
table); the strings themselves are the ``DATA_005776``.. sequence.

Usage: tools/gen-equipment-table.py ../jjffe-master/ffedat.asm
"""

import re
import sys


def main() -> int:
    if len(sys.argv) not in (2, 3):
        print(__doc__)
        return 2
    lines = open(sys.argv[1], encoding="latin-1").read().splitlines()

    start = next(i for i, l in enumerate(lines) if l.strip().startswith("DATA_005289:"))
    data = []
    for line in lines[start:]:
        m = re.match(r"\s*db\s+(.*)", line)
        if not m:
            continue
        for token in m.group(1).split(","):
            token = token.split(";")[0].strip()
            if token:
                data.append(int(token, 0))
        if len(data) >= 66 * 22:
            break
    assert len(data) >= 66 * 22, len(data)

    ptr_start = next(
        i for i, l in enumerate(lines) if l.strip().startswith("DATA_005299:")
    )
    pointers = []
    for line in lines[ptr_start + 1 :]:
        m = re.match(r"\s*dd\s+(\w+)", line)
        if not m:
            break
        pointers.append(m.group(1))

    labels = {}
    for i, line in enumerate(lines):
        m = re.match(r"(DATA_\w+):", line.strip())
        if m:
            labels[m.group(1)] = i

    def string(label: str) -> str:
        entry = labels.get(label)
        if entry is None:
            return "?"
        text = []
        for line in lines[entry + 1 :]:
            m = re.match(r"\s*db\s+(.*)", line)
            if not m:
                break
            for token in m.group(1).split(","):
                token = token.split(";")[0].strip()
                if not token:
                    continue
                if token.startswith("'"):
                    text.append(token.strip("'"))
                elif token.startswith("0x"):
                    value = int(token, 16)
                    if value == 0:
                        return "".join(text)
                    if 0x20 <= value < 0x7F:
                        text.append(chr(value))
        return "".join(text)

    categories = ["General", "Cabin", "Laser", "Drive", "Shield", "Missile", "Mining"]
    # The DOS FIRSTENC.EXE (floppy 1.02, file offset 0xc1674) holds the same
    # 1,452 table bytes except one: record 53 ("Class 3 Military Drive") has
    # tech level 0xeb in the DOS binary and 0xd7 in the JJFFE data listing.
    # Follow the DOS release.
    dos_overrides = {53: {0x13: 0xEB}}
    records = []
    for i in range(66):
        r = data[i * 22 : (i + 1) * 22]
        for offset, value in dos_overrides.get(i, {}).items():
            r[offset] = value
        word = lambda at: int.from_bytes(bytes(r[at : at + 4]), "little")
        category = r[0x10]
        records.append(
            (
                string(pointers[0x75 + i]).replace("\\", "\\\\").replace('"', '\\"'),
                word(0),
                word(4),
                word(8),
                categories[category] if category < len(categories) else "General",
                r[0x12],
                r[0x13],
                r[0x14],
                r[0x11],
            )
        )

    out = []
    out.append("//! The original's equipment table, generated from `ffedat.asm`.")
    out.append("//!")
    out.append("//! `DATA_005289` is 66 records of 22 bytes (`ffedat.asm:6425`); F383 (`ffe.asm:28564`)")
    out.append("//! lists them by tech level and F392 (`ffe.asm:28998`) dispatches to the category")
    out.append("//! handlers. Generated by `tools/gen-equipment-table.py`; do not edit by hand.")
    out.append("//! Record 53's tech level follows the DOS executable (0xeb), not the listing (0xd7).")
    out.append("")
    out.append("use crate::equipment::{Category, Equipment};")
    out.append("")
    out.append("/// `DATA_005289`'s 66 records, in table order.")
    out.append("pub const EQUIPMENT: [Equipment; 66] = [")
    for name, price, removal, mass, category, code, tech, used, flags in records:
        out.append(
            f'    Equipment {{ name: "{name}", price: {price}, removal: {removal}, '
            f"mass: {mass}, category: Category::{category}, code: 0x{code:02x}, "
            f"tech_level: {tech}, used: {'true' if used else 'false'}, flags: 0x{flags:02x} }},"
        )
    out.append("];")
    out.append("")
    text = "\n".join(out)
    if len(sys.argv) == 3:
        with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as file:
            file.write(text + "\n")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
